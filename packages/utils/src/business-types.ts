export type BusinessTypeKey = (typeof BUSINESS_TYPES)[number]["key"]
export function findBusinessType(key: unknown): BusinessType | undefined {
  return BUSINESS_TYPES.find((t) => t.key === key)
}
export function isBusinessTypeKey(key: unknown): key is BusinessTypeKey {
  return Boolean(findBusinessType(key))
}
export function defaultBusinessOffer(
  keys: readonly string[],
): BusinessOperatingModel {
  const offers = new Set(
    keys.map((k) => findBusinessType(k)?.operatingModel).filter(Boolean),
  )
  return offers.size === 1
    ? ([...offers][0] ?? "products_and_services")
    : "products_and_services"
}
export function groupBusinessTypes(keys: readonly string[]): string[][] {
  const groups = new Map<string, string[]>()
  for (const key of new Set(keys)) {
    const type = findBusinessType(key)
    if (!type) continue
    const group = groups.get(type.group) ?? []
    group.push(key)
    groups.set(type.group, group)
  }
  return [...groups.values()]
}
