export type CapabilityId = (typeof capabilityManifest)[number]["id"]
export const writeCapabilities = capabilityManifest.filter(
  (capability): capability is Extract<typeof capability, WriteCapability> =>
    capability.mode === "write",
)
export function capabilityForAction(action: string) {
  const capability = writeCapabilities.find((entry) => entry.action === action)
  if (!capability) throw Error(`No capability for action ${action}`)
  return capability
}
